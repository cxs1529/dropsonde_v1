/**
 * ==============================================================================
 * @file    web_server.c
 * @brief   Wi-Fi Access Point, HTTP Server, and RF Power Manager.
 * 
 * @details
 * Hosts RESTful HTTP endpoints for interacting with the SD card:
 * - `/` : Serves embedded `index.html` from flash.
 * - `/api/live` : Outputs 500ms JSON telemetry array for the NOAA CSS Grid.
 * - `/api/list` : Streams chunked JSON arrays containing file lists and metadata.
 * - `/download` : Serves file downloads (`application/octet-stream`).
 * - `/view` : Displays log content in a browser tab (`text/plain`).
 * - `/api/manage`: Deletes data files and `.META` files simultaneously.
 * 
 * Evaluates GPIO 2 with a 10-second debounce to completely turn off the 
 * Wi-Fi RF transmitter (`esp_wifi_stop()`) to save battery power (~90mA savings).
 * While active, prints a 30-second repeating banner to remind the user how to connect.
 * ==============================================================================
 */

#include "web_server.h"
#include "dns_server.h"
#include "config.h"
#include "esp_log.h"
#include "esp_wifi.h"
#include "esp_http_server.h"
#include "driver/gpio.h"
#include <stdio.h>
#include <string.h>
#include <sys/unistd.h>
#include <sys/stat.h>
#include <dirent.h>

static const char *TAG = "WEB_SERVER";

// HTTPD Subsystem handle
static httpd_handle_t web_server_handle = NULL;

/**
 * Pointers to the embedded index.html file generated by CMake EMBED_TXTFILES.
 * This allows us to serve the HTML file directly from the ESP32's flash memory.
 */
extern const uint8_t index_html_start[] asm("_binary_index_html_start");
extern const uint8_t index_html_end[]   asm("_binary_index_html_end");

/** 
 * @brief Serves the main HTML User Interface.
 */
static esp_err_t index_get_handler(httpd_req_t *req) {
    httpd_resp_set_type(req, "text/html");
    const size_t html_size = (index_html_end - index_html_start);
    return httpd_resp_send(req, (const char *)index_html_start, html_size);
}

/** 
 * @brief Serves discrete 500ms JSON telemetry fields for the NOAA Dashboard Grid.
 * Uses `xSemaphoreTake` to ensure thread-safe reads while the GPS parser updates.
 */
static esp_err_t live_api_get_handler(httpd_req_t *req) {
    char json_resp[512]; 
    gps_msg_t local_data; 
    bool local_logging;
    char local_active_file[32];

    // Mutex Lock: Wait indefinitely until the SD Logger task releases the variables
    xSemaphoreTake(live_data_mutex, portMAX_DELAY);
    memcpy(&local_data, &live_gps_data, sizeof(gps_msg_t));
    local_logging = live_is_logging;
    strncpy(local_active_file, live_active_file, sizeof(local_active_file));
    xSemaphoreGive(live_data_mutex); // Unlock immediately

    snprintf(json_resp, sizeof(json_resp), 
        "{\"date\":\"%02d/%02d/%02d\",\"time\":\"%02d:%02d:%02d\",\"lat\":\"%.6f\",\"lon\":\"%.6f\",\"pdop\":\"%.1f\",\"fix\":\"%s\",\"logging\":%s,\"active_file\":\"%s\"}", 
        local_data.month, local_data.day, local_data.year, local_data.hour, local_data.min, local_data.sec, 
        local_data.lat, local_data.lon, local_data.pdop, local_data.fix_desc, local_logging ? "true" : "false", local_active_file);

    httpd_resp_set_type(req, "application/json");
    return httpd_resp_send(req, json_resp, strlen(json_resp));
}

/** 
 * @brief Lists files and O(1) metadata using HTTP Chunked Encoding.
 * Streams JSON fragments line-by-line so memory allocation remains minimal.
 */
static esp_err_t list_get_handler(httpd_req_t *req) {
    DIR *dir = opendir(DATA_DIR);
    if (!dir) { httpd_resp_send_500(req); return ESP_FAIL; }
    
    httpd_resp_set_type(req, "application/json");
    httpd_resp_send_chunk(req, "[", 1); // Start JSON array
    
    struct dirent *ent; 
    bool first_item = true; 
    char chunk[512];
    
    while ((ent = readdir(dir)) != NULL) {
        // Read file size
        struct stat st; 
        char path[300]; 
        snprintf(path, sizeof(path), "%s/%s", DATA_DIR, ent->d_name);
        stat(path, &st);
        
        // Read corresponding O(1) Metadata
        char meta_path[300]; 
        snprintf(meta_path, sizeof(meta_path), "%s/%s.META", META_DIR, ent->d_name);
        long lines = 0; 
        char first_line[64] = "N/A", last_line[64] = "N/A";
        
        FILE *fm = fopen(meta_path, "r");
        if (fm) {
            char buf[64];
            if (fgets(buf, sizeof(buf), fm)) lines = atol(buf);
            if (fgets(buf, sizeof(buf), fm)) { buf[strcspn(buf, "\r\n")] = 0; strncpy(first_line, buf, 63); }
            if (fgets(buf, sizeof(buf), fm)) { buf[strcspn(buf, "\r\n")] = 0; strncpy(last_line, buf, 63); }
            fclose(fm);
        }
        
        // Stream the chunk to the browser
        snprintf(chunk, sizeof(chunk), "%s{\"name\":\"%s\",\"size\":%ld,\"lines\":%ld,\"first\":\"%s\",\"last\":\"%s\"}", 
                 first_item ? "" : ",", ent->d_name, st.st_size, lines, first_line, last_line);
        httpd_resp_send_chunk(req, chunk, strlen(chunk));
        first_item = false;
    }
    closedir(dir);
    
    httpd_resp_send_chunk(req, "]", 1); // Close JSON array
    httpd_resp_send_chunk(req, NULL, 0); // End chunked transmission
    return ESP_OK;
}

/** 
 * @brief Streams file downloads over HTTP in 1KB chunks.
 * Sets Content-Type to `application/octet-stream` to force a browser download.
 */
static esp_err_t download_get_handler(httpd_req_t *req) {
    char filepath[256]; char filename[128];
    if (httpd_req_get_url_query_str(req, filename, sizeof(filename)) != ESP_OK ||
        httpd_query_key_value(filename, "file", filename, sizeof(filename)) != ESP_OK) {
        httpd_resp_send_404(req); return ESP_FAIL;
    }
    snprintf(filepath, sizeof(filepath), "%s/%s", DATA_DIR, filename);
    FILE *fd = fopen(filepath, "r");
    if (!fd) { httpd_resp_send_404(req); return ESP_FAIL; }

    httpd_resp_set_type(req, "application/octet-stream");
    char chunk[1024]; size_t chunksize;
    
    // Read and stream in a loop to preserve ESP32 RAM
    do {
        chunksize = fread(chunk, 1, sizeof(chunk), fd);
        if (chunksize > 0) httpd_resp_send_chunk(req, chunk, chunksize);
    } while (chunksize != 0);
    fclose(fd);
    
    httpd_resp_send_chunk(req, NULL, 0); 
    return ESP_OK;
}

/** 
 * @brief Streams file contents to a new browser tab.
 * Sets Content-Type to `text/plain` so the browser renders the text natively.
 */
static esp_err_t view_get_handler(httpd_req_t *req) {
    char filepath[256]; char filename[128];
    if (httpd_req_get_url_query_str(req, filename, sizeof(filename)) != ESP_OK ||
        httpd_query_key_value(filename, "file", filename, sizeof(filename)) != ESP_OK) {
        httpd_resp_send_404(req); return ESP_FAIL;
    }
    snprintf(filepath, sizeof(filepath), "%s/%s", DATA_DIR, filename);
    FILE *fd = fopen(filepath, "r");
    if (!fd) { httpd_resp_send_404(req); return ESP_FAIL; }

    httpd_resp_set_type(req, "text/plain"); 
    char chunk[1024]; size_t chunksize;
    do {
        chunksize = fread(chunk, 1, sizeof(chunk), fd);
        if (chunksize > 0) httpd_resp_send_chunk(req, chunk, chunksize);
    } while (chunksize != 0);
    fclose(fd);
    httpd_resp_send_chunk(req, NULL, 0); 
    return ESP_OK;
}

/** 
 * @brief Handles file deletion commands from the UI.
 * Unlinks the raw data file AND the metadata file, printing a log to the terminal.
 * Safely rejects requests to delete the currently active log file.
 */
static esp_err_t manage_post_handler(httpd_req_t *req) {
    char query[256]; char action[32], file[64], path[128];
    if (httpd_req_get_url_query_str(req, query, sizeof(query)) != ESP_OK) return ESP_FAIL;
    httpd_query_key_value(query, "action", action, sizeof(action));
    httpd_query_key_value(query, "file", file, sizeof(file));

    // Security Check: Ensure user cannot delete the active file
    xSemaphoreTake(live_data_mutex, portMAX_DELAY);
    bool is_protected = (strcmp(file, live_active_file) == 0);
    xSemaphoreGive(live_data_mutex);

    if (strcmp(action, "delete") == 0) {
        if (is_protected) {
            ESP_LOGW(TAG, "Rejected attempt to delete ACTIVE file: %s", file);
            httpd_resp_send_err(req, HTTPD_403_FORBIDDEN, "Cannot delete the active logging file.");
            return ESP_FAIL;
        }

        // Construct full paths
        snprintf(path, sizeof(path), "%s/%s", DATA_DIR, file);
        char meta_path[128];
        snprintf(meta_path, sizeof(meta_path), "%s/%s.META", META_DIR, file);

        // Delete raw data file
        if (unlink(path) == 0) {
            printf("\n[WEB SERVER DELETE] Successfully deleted DATA file: %s\n", path);
        } else {
            printf("\n[WEB SERVER DELETE] Failed to delete DATA file: %s\n", path);
        }

        // Delete metadata file
        if (unlink(meta_path) == 0) {
            printf("[WEB SERVER DELETE] Successfully deleted META file: %s\n\n", meta_path);
        } else {
            printf("[WEB SERVER DELETE] META file not found or failed to delete: %s\n\n", meta_path);
        }
    }
    
    httpd_resp_sendstr(req, "OK");
    return ESP_OK;
}

/**
 * @brief Boots the baseline network drivers and AP configuration.
 * Does NOT start the RF transmitter (esp_wifi_start is called by the manager task).
 */
void init_wifi_base(void) {
    esp_netif_init();
    esp_event_loop_create_default();
    esp_netif_create_default_wifi_ap();

    wifi_init_config_t cfg = WIFI_INIT_CONFIG_DEFAULT();
    esp_wifi_init(&cfg);

    wifi_config_t wifi_config = {
        .ap = {
            .ssid = WIFI_AP_SSID, 
            .ssid_len = strlen(WIFI_AP_SSID),
            .channel = 1, 
            .password = WIFI_AP_PASS,
            .max_connection = MAX_STA_CONN, 
            .authmode = WIFI_AUTH_WPA_WPA2_PSK
        },
    };
    esp_wifi_set_mode(WIFI_MODE_AP);
    esp_wifi_set_config(WIFI_IF_AP, &wifi_config);
}

/**
 * @brief Initializes the HTTP daemon and registers all URI endpoints.
 */
static void start_webserver(void) {
    httpd_config_t config = HTTPD_DEFAULT_CONFIG();
    config.uri_match_fn = httpd_uri_match_wildcard;
    
    if (httpd_start(&web_server_handle, &config) == ESP_OK) {
        httpd_uri_t index_uri = { .uri = "/", .method = HTTP_GET, .handler = index_get_handler };
        httpd_uri_t live_uri  = { .uri = "/api/live", .method = HTTP_GET, .handler = live_api_get_handler };
        httpd_uri_t list_uri  = { .uri = "/api/list", .method = HTTP_GET, .handler = list_get_handler };
        httpd_uri_t dl_uri    = { .uri = "/download*", .method = HTTP_GET, .handler = download_get_handler };
        httpd_uri_t view_uri  = { .uri = "/view*", .method = HTTP_GET, .handler = view_get_handler };
        httpd_uri_t mng_uri   = { .uri = "/api/manage*", .method = HTTP_POST, .handler = manage_post_handler };
        
        httpd_register_uri_handler(web_server_handle, &index_uri);
        httpd_register_uri_handler(web_server_handle, &live_uri);
        httpd_register_uri_handler(web_server_handle, &list_uri);
        httpd_register_uri_handler(web_server_handle, &dl_uri);
        httpd_register_uri_handler(web_server_handle, &view_uri);
        httpd_register_uri_handler(web_server_handle, &mng_uri);
    }
}

/** 
 * @brief RTOS Task managing Wi-Fi hardware power state with 10s debounce.
 * @details
 * Monitors the physical Wi-Fi toggle switch. After 10 seconds of stability,
 * it brings up the Access Point, HTTP Web Server, and Captive DNS. Prints
 * detailed connection instructions to the console every 30 seconds while active.
 */
void wifi_manager_task(void *arg) {
    bool logical_wifi_state = false;
    TickType_t pause_tick = 0, resume_tick = 0;
    TickType_t last_reminder_tick = 0; // Tracks the 30-second repeating banner
    bool last_physical_state = (gpio_get_level(WIFI_SWITCH_PIN) == 0);

    while (1) {
        vTaskDelay(pdMS_TO_TICKS(200)); // Check switch every 200ms
        
        bool physical_switch_is_on = (gpio_get_level(WIFI_SWITCH_PIN) == 0);
        TickType_t current_time = xTaskGetTickCount();

        // Edge Changes for Printing
        if (physical_switch_is_on && !last_physical_state) {
            printf("\n((( WI-FI SWITCH ACTIVE. Waiting 10 seconds to power up antenna... )))\n\n");
        } else if (!physical_switch_is_on && last_physical_state) {
            printf("\n((( WI-FI SWITCH PAUSED. Waiting 10 seconds to power down antenna... )))\n\n");
        }
        last_physical_state = physical_switch_is_on;

        // 10-Second Debounce Logic
        if (!physical_switch_is_on) {
            resume_tick = 0;
            if (logical_wifi_state) {
                if (pause_tick == 0) pause_tick = current_time;
                
                // Switch verified OFF for 10 continuous seconds
                if ((current_time - pause_tick) >= pdMS_TO_TICKS(10000)) {
                    logical_wifi_state = false;
                    printf("((( Disabling Wi-Fi, Web Server, and DNS Server to save battery. )))\n");
                    
                    // Gracefully stop HTTP handlers and DNS socket before cutting RF power
                    if (web_server_handle) { 
                        httpd_stop(web_server_handle); 
                        web_server_handle = NULL; 
                    }
                    stop_dns_server(); 
                    esp_wifi_stop(); // Completely disables RF transmitter
                }
            }
        } else {
            pause_tick = 0;
            if (!logical_wifi_state) {
                if (resume_tick == 0) resume_tick = current_time;
                
                // Switch verified ON for 10 continuous seconds
                if ((current_time - resume_tick) >= pdMS_TO_TICKS(10000)) {
                    logical_wifi_state = true;
                    last_reminder_tick = current_time; // Initialize banner timer
                    
                    // Boot up RF transmitter, HTTP Server, and Captive DNS
                    esp_wifi_start();
                    start_webserver();
                    start_dns_server();
                    
                    // Print initial instructions to the console for the user
                    printf("\n======================================================================\n");
                    printf("  NOAA DASHBOARD ACTIVE\n");
                    printf("  1. Connect your device to Wi-Fi Network : %s\n", WIFI_AP_SSID);
                    printf("  2. Open any web browser and navigate to : http://aomldropsonde.com\n");
                    printf("     (Or use the direct IP Address        : http://192.168.4.1)\n");
                    printf("======================================================================\n\n");
                }
            } else {
                // Currently in ACTIVE state. Print repeating banner every 30 seconds.
                if ((current_time - last_reminder_tick) >= pdMS_TO_TICKS(30000)) {
                    printf("\n======================================================================\n");
                    printf("  NOAA DASHBOARD ACTIVE - REMINDER\n");
                    printf("  1. Connect your device to Wi-Fi Network : %s\n", WIFI_AP_SSID);
                    printf("  2. Open any web browser and navigate to : http://aomldropsonde.com\n");
                    printf("     (Or use the direct IP Address        : http://192.168.4.1)\n");
                    printf("======================================================================\n\n");
                    last_reminder_tick = current_time;
                }
            }
        }
    }
}